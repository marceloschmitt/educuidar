-- Autorizações de entrada/saída fora do horário
-- Podem ser criadas pelo responsável (portal) ou pela escola (telefone, e-mail etc.)

CREATE TABLE IF NOT EXISTS autorizacoes_responsavel (
    id INT AUTO_INCREMENT PRIMARY KEY,
    responsavel_id INT NULL,
    origem ENUM('portal', 'escola') NOT NULL DEFAULT 'portal',
    aluno_id INT NOT NULL,
    tipo ENUM('entrada_fora_horario', 'saida_fora_horario') NOT NULL,
    data_autorizacao DATE NOT NULL,
    hora TIME NOT NULL,
    justificativa TEXT NOT NULL,
    autorizado_por_nome VARCHAR(200) NULL,
    meio_autorizacao VARCHAR(50) NULL,
    registrado_por INT NULL,
    status ENUM('pendente', 'ocorrido', 'nao_ocorrido') NOT NULL DEFAULT 'pendente',
    confirmado_por INT NULL,
    confirmado_em TIMESTAMP NULL,
    evento_id INT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_aluno (aluno_id),
    INDEX idx_responsavel (responsavel_id),
    INDEX idx_origem (origem),
    INDEX idx_registrado_por (registrado_por),
    INDEX idx_data (data_autorizacao),
    INDEX idx_status (status),
    INDEX idx_tipo (tipo),
    INDEX idx_evento (evento_id),
    FOREIGN KEY (responsavel_id) REFERENCES responsaveis(id) ON DELETE CASCADE,
    FOREIGN KEY (aluno_id) REFERENCES alunos(id) ON DELETE CASCADE,
    FOREIGN KEY (registrado_por) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (confirmado_por) REFERENCES users(id) ON DELETE SET NULL,
    FOREIGN KEY (evento_id) REFERENCES eventos(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
